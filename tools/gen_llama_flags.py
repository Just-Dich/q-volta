#!/usr/bin/env python3
"""Generate src/server/llama_flags.inc from `llama-server --help` (llama.cpp 9d6f04f).
usage: gen_llama_flags.py help.txt src/server/llama_flags.inc"""
import re, sys, json
lines = open(sys.argv[1], encoding="utf-8").read().split("\n")
entries, cur, section = [], None, ""
for ln in lines:
    m = re.match(r"^----- (.*) -----", ln)
    if m:
        section = m.group(1); cur = None; continue
    if ln.startswith("-"):
        spec = ln[:40].rstrip() if len(ln) > 40 and ln[38:40] == "  " else ln.strip()
        cur = {"spec": spec, "section": section, "text": ln[40:] if len(ln) > 40 and ln[38:40] == "  " else ""}
        entries.append(cur)
    elif cur is not None and ln.startswith(" "):
        cur["text"] += " " + ln.strip()
    else:
        cur = None
out = []
for e in entries:
    toks = e["spec"].split()
    names, meta = [], []
    for t in toks:
        t2 = t.rstrip(",")
        if t2.startswith("-") and not meta:
            names.append(t2)
        else:
            meta.append(t)
    mv = " ".join(meta)
    arg = 0
    if mv:
        arg = 2 if re.fullmatch(r"\[(on\|off\|auto|on\|off|true\|false)\]", mv) or mv == "[on|off|auto]" else 1
    envs = re.findall(r"LLAMA_[A-Z0-9_]+", " ".join(re.findall(r"\(env: ([^)]*)\)", e["text"])))
    # "--no-X" spellings of a boolean pair
    out.append({"names": names, "arg": arg, "env": envs, "section": e["section"], "meta": mv, "desc": re.sub(r"\(env: [^)]*\)", "", e["text"]).strip()})
json.dump(out, open(sys.argv[2].replace(".inc", ".json"), "w"), indent=0)
with open(sys.argv[2], "w") as f:
    f.write("// generated by tools/gen_llama_flags.py from llama-server --help (llama.cpp 9d6f04f): spelling table\n")
    for o in out:
        ns = ",".join(json.dumps(n) for n in o["names"])
        f.write("{{%s}, %d, %s},\n" % (ns, o["arg"], json.dumps(" ".join(o["env"]))))
print(len(out), "flags", sum(1 for o in out if o["env"]), "with env")
