#!/usr/bin/env python3
"""Generate src/tokenizer/unicode_tables.inc from Python's unicodedata (Unicode 15.0 with CPython 3.12).

Tables: general-category ranges for L, M, N (the \\p{L} \\p{M} \\p{N} classes of the Qwen split pattern),
canonical decompositions + combining classes + primary composites for NFC normalisation.
Usage: python3 -I tools/gen_unicode_tables.py > src/tokenizer/unicode_tables.inc
"""
import sys
import unicodedata as ud

MAXCP = 0x110000


def ranges(pred):
    out, start = [], None
    for cp in range(MAXCP):
        ok = pred(cp)
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAXCP - 1))
    return out


def cat_ranges(letter):
    return ranges(lambda cp: not (0xD800 <= cp <= 0xDFFF) and ud.category(chr(cp))[0] == letter)


def emit_pairs(name, pairs):
    print(f"static const uint32_t {name}[][2] = {{")
    line = []
    for a, b in pairs:
        line.append(f"{{0x{a:X},0x{b:X}}}")
        if len(line) == 8:
            print("  " + ",".join(line) + ",")
            line = []
    if line:
        print("  " + ",".join(line) + ",")
    print("};")
    print(f"static const size_t {name}_n = sizeof({name}) / sizeof({name}[0]);")


def main():
    print("// GENERATED by tools/gen_unicode_tables.py (Unicode %s). Do not edit." % ud.unidata_version)
    emit_pairs("kCatL", cat_ranges("L"))
    emit_pairs("kCatM", cat_ranges("M"))
    emit_pairs("kCatN", cat_ranges("N"))
    # combining classes: (cp, ccc) runs -> store as (lo, hi, ccc) triples flattened into pairs with packed value
    ccc = [(cp, ud.combining(chr(cp))) for cp in range(MAXCP) if not (0xD800 <= cp <= 0xDFFF) and ud.combining(chr(cp))]
    runs = []
    for cp, c in ccc:
        if runs and runs[-1][1] == cp - 1 and runs[-1][2] == c:
            runs[-1][1] = cp
        else:
            runs.append([cp, cp, c])
    print("static const uint32_t kCcc[][3] = {")
    for i in range(0, len(runs), 6):
        print("  " + ",".join("{0x%X,0x%X,%d}" % tuple(r) for r in runs[i:i + 6]) + ",")
    print("};")
    print("static const size_t kCcc_n = sizeof(kCcc) / sizeof(kCcc[0]);")
    # full canonical decompositions (NFD of the single char); Hangul handled algorithmically
    dec = []
    pool = []
    for cp in range(MAXCP):
        if 0xD800 <= cp <= 0xDFFF or 0xAC00 <= cp <= 0xD7A3:
            continue
        d = ud.normalize("NFD", chr(cp))
        if d != chr(cp):
            dec.append((cp, len(pool), len(d)))
            pool.extend(ord(x) for x in d)
    print("static const uint32_t kDec[][3] = {  // cp, offset into kDecPool, length")
    for i in range(0, len(dec), 6):
        print("  " + ",".join("{0x%X,%d,%d}" % t for t in dec[i:i + 6]) + ",")
    print("};")
    print("static const size_t kDec_n = sizeof(kDec) / sizeof(kDec[0]);")
    print("static const uint32_t kDecPool[] = {")
    for i in range(0, len(pool), 12):
        print("  " + ",".join("0x%X" % x for x in pool[i:i + 12]) + ",")
    print("};")
    # primary composites: single-step canonical decomposition of length 2 that NFC recomposes
    comp = []
    for cp in range(MAXCP):
        if 0xD800 <= cp <= 0xDFFF or 0xAC00 <= cp <= 0xD7A3:
            continue
        raw = ud.decomposition(chr(cp))
        if not raw or raw.startswith("<"):
            continue
        parts = [int(x, 16) for x in raw.split()]
        if len(parts) != 2:
            continue
        if ud.normalize("NFC", chr(parts[0]) + chr(parts[1])) == chr(cp):
            comp.append((parts[0], parts[1], cp))
    comp.sort()
    print("static const uint32_t kComp[][3] = {  // first, second, composite (sorted)")
    for i in range(0, len(comp), 6):
        print("  " + ",".join("{0x%X,0x%X,0x%X}" % t for t in comp[i:i + 6]) + ",")
    print("};")
    print("static const size_t kComp_n = sizeof(kComp) / sizeof(kComp[0]);")


if __name__ == "__main__":
    main()
